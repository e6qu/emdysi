def slop_pack():
    """bheijden/slop's regex rules that fire on any match, as `regex`
    rules; each rule's tests become its examples, and a rule is kept only
    if its pattern finds every `hit` within one sentence, as emdysi
    matches, and nothing in any `miss` (checked
    with the `regex` module, and again by the test suite). Rules on counts
    per unit of text, and the other match kinds (chains, echoes,
    anaphora), are left out: emdysi's own ai-tells pack covers those."""
    import json

    import regex

    lines = [
        "# Generated by scripts/import-rules.py from data/slop; do not edit.",
        "# Source: bheijden/slop (Apache-2.0; the wikipedia-ai set CC BY-SA 4.0).",
        "",
        "[pack]",
        'name = "slop"',
        "description = "
        + q("Phrases and patterns of machine-written prose from bheijden/slop's rule sets (opt-in)."),
    ]
    seen = set()
    for name, attribution in SLOP:
        data = json.loads((ROOT / f"data/slop/rules/{name}.json").read_text(encoding="utf-8"))
        for r in data["rules"]:
            m = r.get("match", {})
            if m.get("kind") != "regex" or r.get("notable") != {">": 0}:
                continue
            pat = m["pattern"]
            flags = m.get("flags", "")
            pat = ("(?i)" if "i" in flags else "") + pat
            tests = r.get("tests", {})
            hits, misses = tests.get("hit", []), tests.get("miss", [])
            try:
                c = regex.compile(pat)
            except regex.error:
                continue
            # emdysi matches a pattern within one sentence at a time.
            def found(text):
                return any(c.search(t) for t in regex.split(r"(?<=[.!?])\s+(?=\W*[A-Z])", text))

            if not hits or not all(found(h) for h in hits) or any(c.search(x) for x in misses):
                continue
            rid = f"slop.{kebab(r['id'])}"
            if rid in seen:
                rid = f"slop.{name}-{kebab(r['id'])}"
            seen.add(rid)
            severity = "warning" if r.get("severity") in ("error", "warn") else "suggestion"
            message = (r.get("name") or r["id"]).strip()
            if r.get("suggest"):
                message += ": " + str(r["suggest"]).strip()
            lines += [
                "",
                "[[rule]]",
                "id = " + q(rid),
                'kind = "regex"',
                "severity = " + q(severity),
                "message = " + q(message),
            ]
            if r.get("description"):
                lines.append("description = " + q(str(r["description"]).strip()))
            lines += [
                "source = " + q(f"https://github.com/bheijden/slop/blob/6af32460028c96e5144c08fff2e2d44a2bbed9be/rules/{name}.json ({r['id']}); data/slop/rules/{name}.json"),
                "license = " + q(attribution),
                "pattern = " + q(pat),
                "examples = [" + ", ".join(q(h + "\n") for h in hits) + "]",
            ]
            if misses:
                lines.append("acceptable = [" + ", ".join(q(x + "\n") for x in misses) + "]")
    lines.append("")
    return "\n".join(lines)


